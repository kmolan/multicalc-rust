//! Emits `tools/embedded-smoke/src/fixtures.rs`: a `no_std` file of `const`
//! goldens for the on-target smoke checks, taken bit-exact from the committed
//! QA fixtures. The firmware asserts against the identical values the host
//! goldens hold, so the two share one source of truth.
//!
//! Run `cargo run -p multicalc-qa --bin gen_smoke_fixtures`. The output is
//! deterministic (fixed ordering and formatting), so CI can regenerate it and
//! diff against the committed copy.

use std::fmt::Write as _;
use std::path::Path;

use multicalc_qa::load::load_dir;
use multicalc_qa::schema::{Fixture, Tol, Value};

const HEADER: &str = "// GENERATED by `cargo run -p multicalc-qa --bin gen_smoke_fixtures`. Do not edit.\n\
     // Goldens for the on-target smoke checks, taken bit-exact from tools/qa/fixtures.\n\
     // SVD golden: linalg/svd_3x3. LM golden: optimization/rosenbrock.\n\
     // Wien golden: root_finding/wien_newton.\n\
     // Kalman golden: estimation/kalman_filter_constant_velocity_one_dimensional.\n\
     // Coordinated-turn golden: estimation/extended_kalman_filter_coordinated_turn_fusion.\n\
     // Polynomial-roots golden: polynomial/roots_quartic_four_real.\n\
     // Trajectory golden: motion/minimum_snap_three_segments_3d.\n\
     // Franka golden: kinematics/franka_panda_seven_joint.\n\
     // Reduced (canary) builds use a subset, so some consts may be unused.\n\
     // Left unformatted: this file's shape comes from the generator, and rustfmt would\n\
     // collapse some literals so a regenerate-and-diff check could never come out clean.\n\
     #![cfg_attr(rustfmt, rustfmt::skip)]\n\
     #![allow(clippy::unreadable_literal)]\n\
     #![allow(dead_code)]\n\n";

#[must_use]
fn find<'a>(fixtures: &'a [Fixture], case: &str) -> &'a Fixture {
    fixtures
        .iter()
        .find(|f| f.case == case)
        .unwrap_or_else(|| unreachable!("fixture case {case:?} not found"))
}

/// A scalar as a bit-exact `f64` literal.
#[must_use]
fn scalar_lit(v: &Value) -> String {
    format!(
        "f64 = f64::from_bits(0x{:016x});\n",
        v.as_scalar().to_bits()
    )
}

/// A vector as a bit-exact `[f64; N]` literal, one element per line.
#[must_use]
fn vector_lit(v: &Value) -> String {
    let data = v.as_vector();
    let mut s = format!("[f64; {}] = [\n", data.len());
    for &x in &data {
        let _ = writeln!(s, "    f64::from_bits(0x{:016x}),", x.to_bits());
    }
    s.push_str("];\n");
    s
}

/// A raw slice, rather than a whole fixture value, as a bit-exact `[f64; N]` literal — for a
/// golden taken from part of a larger fixture field rather than all of it.
#[must_use]
fn vector_lit_raw(data: &[f64]) -> String {
    let mut s = format!("[f64; {}] = [\n", data.len());
    for &x in data {
        let _ = writeln!(s, "    f64::from_bits(0x{:016x}),", x.to_bits());
    }
    s.push_str("];\n");
    s
}

/// A matrix as a bit-exact `[[f64; C]; R]` literal, shaped from the fixture so
/// the emitted literal cannot disagree with the data it holds.
#[must_use]
fn matrix_lit(v: &Value) -> String {
    let (rows, cols, data) = v.as_matrix();
    let mut s = format!("[[f64; {cols}]; {rows}] = [\n");
    for r in 0..rows {
        s.push_str("    [\n");
        for c in 0..cols {
            let _ = writeln!(
                s,
                "        f64::from_bits(0x{:016x}),",
                data[r * cols + c].to_bits()
            );
        }
        s.push_str("    ],\n");
    }
    s.push_str("];\n");
    s
}

/// Appends one documented constant, followed by a blank line.
fn emit(out: &mut String, doc: &str, name: &str, literal: &str) {
    let _ = write!(out, "/// {doc}\npub const {name}: {literal}\n");
}

/// Appends one documented constant with nothing after it, for constants that
/// belong with the one that follows.
fn emit_grouped(out: &mut String, doc: &str, name: &str, literal: &str) {
    let _ = write!(out, "/// {doc}\npub const {name}: {literal}");
}

/// Appends the absolute and relative bounds for one check.
fn emit_tolerance(out: &mut String, check: &str, prefix: &str, t: Tol) {
    let _ = write!(
        out,
        "/// Comparison tolerance for the {check} check (from the fixture's f64 tolerance).\n\
         pub const {prefix}_ABS: f64 = {:e};\n\
         pub const {prefix}_REL: f64 = {:e};\n\n",
        t.abs, t.rel,
    );
}

fn main() {
    let linalg = load_dir("linalg");
    let optimization = load_dir("optimization");
    let root_finding = load_dir("root_finding");
    let estimation = load_dir("estimation");

    let svd = find(&linalg, "svd_3x3");
    let rosen = find(&optimization, "rosenbrock");
    let wien = find(&root_finding, "wien_newton");
    let kalman = find(
        &estimation,
        "kalman_filter_constant_velocity_one_dimensional",
    );
    let turn = find(
        &estimation,
        "extended_kalman_filter_coordinated_turn_fusion",
    );
    let polynomial = load_dir("polynomial");
    let motion = load_dir("motion");
    let kinematics = load_dir("kinematics");
    let quartic = find(&polynomial, "roots_quartic_four_real");
    let trajectory = find(&motion, "minimum_snap_three_segments_3d");
    let franka = find(&kinematics, "franka_panda_seven_joint");

    let mut out = String::from(HEADER);

    let (rows, cols) = svd.inputs["A"].shape();
    emit(
        &mut out,
        &format!(
            "Input matrix `A` (row-major {rows}\u{d7}{cols}) for the SVD check, from linalg/svd_3x3."
        ),
        "SVD_3X3_INPUT",
        &matrix_lit(&svd.inputs["A"]),
    );
    emit(
        &mut out,
        "Expected singular values of `SVD_3X3_INPUT`, descending.",
        "SVD_3X3_SINGULAR_VALUES",
        &vector_lit(&svd.expected["singular_values"]),
    );
    emit_tolerance(&mut out, "SVD", "SVD_3X3", svd.tolerances.f64);

    emit(
        &mut out,
        "Initial guess for the Rosenbrock least-squares fit, from optimization/rosenbrock.",
        "ROSENBROCK_X0",
        &vector_lit(&rosen.inputs["x0"]),
    );
    emit(
        &mut out,
        "Expected minimizer of the Rosenbrock fit.",
        "ROSENBROCK_SOLUTION",
        &vector_lit(&rosen.expected["solution"]),
    );
    emit_tolerance(&mut out, "Rosenbrock", "ROSENBROCK", rosen.tolerances.f64);

    emit_grouped(
        &mut out,
        "Newton start for the Wien check, from root_finding/wien_newton.",
        "ROOT_WIEN_X0",
        &scalar_lit(&wien.inputs["start"]),
    );
    emit_grouped(
        &mut out,
        "Expected Wien root (transcendental, so taken bit-exact from the fixture).",
        "ROOT_WIEN_ROOT",
        &scalar_lit(&wien.expected["root"]),
    );
    emit_tolerance(&mut out, "Wien", "ROOT_WIEN", wien.tolerances.f64);

    emit(
        &mut out,
        "Initial state of the linear filter, from estimation/kalman_filter_constant_velocity_one_dimensional.",
        "KALMAN_INITIAL_STATE",
        &vector_lit(&kalman.inputs["initial_state"]),
    );
    emit(
        &mut out,
        "Initial covariance of the linear filter.",
        "KALMAN_INITIAL_COVARIANCE",
        &matrix_lit(&kalman.inputs["initial_covariance"]),
    );
    emit(
        &mut out,
        "State transition of the linear filter.",
        "KALMAN_STATE_TRANSITION",
        &matrix_lit(&kalman.inputs["state_transition"]),
    );
    emit(
        &mut out,
        "Measurement model of the linear filter.",
        "KALMAN_MEASUREMENT_MODEL",
        &matrix_lit(&kalman.inputs["measurement_model"]),
    );
    emit(
        &mut out,
        "Process noise of the linear filter.",
        "KALMAN_PROCESS_NOISE",
        &matrix_lit(&kalman.inputs["process_noise"]),
    );
    emit(
        &mut out,
        "Measurement noise of the linear filter.",
        "KALMAN_MEASUREMENT_NOISE",
        &matrix_lit(&kalman.inputs["measurement_noise"]),
    );
    emit(
        &mut out,
        "The measurement sequence fed to the linear filter, one row per step.",
        "KALMAN_MEASUREMENTS",
        &matrix_lit(&kalman.inputs["measurements"]),
    );
    emit(
        &mut out,
        "Expected state after the whole sequence.",
        "KALMAN_EXPECTED_STATE",
        &vector_lit(&kalman.expected["state"]),
    );
    emit_tolerance(&mut out, "linear filter", "KALMAN", kalman.tolerances.f64);

    emit(
        &mut out,
        "Tick length of the turning-arc model, from estimation/extended_kalman_filter_coordinated_turn_fusion.",
        "COORDINATED_TURN_TIMESTEP",
        &scalar_lit(&turn.inputs["timestep"]),
    );
    emit(
        &mut out,
        "Initial state of the extended filter: `[x, y, heading, speed, turn_rate]`.",
        "COORDINATED_TURN_INITIAL_STATE",
        &vector_lit(&turn.inputs["initial_state"]),
    );
    emit(
        &mut out,
        "Initial covariance of the extended filter.",
        "COORDINATED_TURN_INITIAL_COVARIANCE",
        &matrix_lit(&turn.inputs["initial_covariance"]),
    );
    emit(
        &mut out,
        "Process noise of the extended filter.",
        "COORDINATED_TURN_PROCESS_NOISE",
        &matrix_lit(&turn.inputs["process_noise"]),
    );
    emit(
        &mut out,
        "Measurement noise of the extended filter.",
        "COORDINATED_TURN_MEASUREMENT_NOISE",
        &matrix_lit(&turn.inputs["measurement_noise"]),
    );
    emit(
        &mut out,
        "The position fixes fed to the extended filter, one row per step.",
        "COORDINATED_TURN_MEASUREMENTS",
        &matrix_lit(&turn.inputs["measurements"]),
    );
    emit(
        &mut out,
        "Expected state after the whole sequence.",
        "COORDINATED_TURN_EXPECTED_STATE",
        &vector_lit(&turn.expected["state"]),
    );
    emit_tolerance(
        &mut out,
        "extended filter",
        "COORDINATED_TURN",
        turn.tolerances.f64,
    );

    emit(
        &mut out,
        "Coefficients of x(x − 1)(x − 2)(x − 4), lowest power first, from \
         polynomial/roots_quartic_four_real.",
        "POLYNOMIAL_QUARTIC_COEFFICIENTS",
        &vector_lit(&quartic.inputs["coefficients"]),
    );
    emit(
        &mut out,
        "Expected real roots of that quartic, ascending.",
        "POLYNOMIAL_QUARTIC_ROOTS",
        &vector_lit(&quartic.expected["roots"]),
    );
    emit_tolerance(
        &mut out,
        "polynomial roots",
        "POLYNOMIAL_QUARTIC",
        quartic.tolerances.f64,
    );

    emit(
        &mut out,
        "Segment durations of the planned trajectory, from \
         motion/minimum_snap_three_segments_3d.",
        "MINIMUM_SNAP_DURATIONS",
        &vector_lit(&trajectory.inputs["durations"]),
    );
    emit(
        &mut out,
        "Its segment coefficients, one row per segment and axis (row = segment · 3 + axis).",
        "MINIMUM_SNAP_COEFFICIENTS",
        &matrix_lit(&trajectory.expected["coefficients"]),
    );
    emit(
        &mut out,
        "The times the trajectory is sampled at, shared with the host suite.",
        "MINIMUM_SNAP_SAMPLE_TIMES",
        &vector_lit(&trajectory.inputs["sample_times"]),
    );
    emit(
        &mut out,
        "Position, velocity and acceleration there (row = sample · 3 + order).",
        "MINIMUM_SNAP_SAMPLED_STATES",
        &matrix_lit(&trajectory.expected["sampled_states"]),
    );
    emit_tolerance(
        &mut out,
        "trajectory",
        "MINIMUM_SNAP",
        trajectory.tolerances.f64,
    );

    // `joint_positions` is one row per configuration, one column per body (welds included); the
    // first nine columns of row 0 are the chain down to the hand, in the same slot order the
    // checked-in Franka model uses. `world_positions` is configuration-major then body-major, so
    // configuration 0's hand (body index 8) sits at row 8.
    let (_, _, joint_positions) = franka.inputs["joint_positions"].as_matrix();
    let (_, _, world_positions) = franka.expected["world_positions"].as_matrix();
    emit(
        &mut out,
        "The Franka's nine slot readings at configuration 0, from \
         kinematics/franka_panda_seven_joint (the base and hand welds read zero).",
        "FRANKA_JOINT_READINGS",
        &vector_lit_raw(&joint_positions[..9]),
    );
    emit(
        &mut out,
        "Where MuJoCo puts the Franka's hand at that configuration.",
        "FRANKA_HAND_POSITION",
        &vector_lit_raw(&world_positions[8 * 3..8 * 3 + 3]),
    );

    // The last constant ends the file, so drop the blank line after it.
    while out.ends_with("\n\n") {
        out.pop();
    }

    let dest = Path::new(env!("CARGO_MANIFEST_DIR")).join("../embedded-smoke/src/fixtures.rs");
    std::fs::write(&dest, out).unwrap_or_else(|e| unreachable!("write {dest:?}: {e}"));
    println!("wrote {}", dest.display());
}
