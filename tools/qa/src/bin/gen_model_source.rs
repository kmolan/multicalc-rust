//! Writes the Franka Panda arm out as Rust source for the on-target smoke run, so the bare-metal
//! side never reads a model file.
//!
//! Run `cargo run -p multicalc-qa --bin gen_model_source`. The output is deterministic, so CI
//! regenerates it and diffs against the committed file.

use std::path::Path;

use multicalc_robot_model::{GeneratedScalar, RustSourceOptions};

fn main() {
    let input = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../third_party/menagerie/franka_emika_panda/panda.xml");
    let output =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../embedded-smoke/src/franka_panda_model.rs");

    let model =
        multicalc_robot_model::mjcf::load_path(&input).unwrap_or_else(|e| unreachable!("load {input:?}: {e}"));
    let options = RustSourceOptions::new("franka_panda_arm")
        .with_scalar(GeneratedScalar::F32)
        .with_capacity(9)
        .with_tip("hand")
        .with_header(
            "GENERATED by `cargo run -p multicalc-qa --bin gen_model_source`. Do not edit.\n\
             // Source: third_party/menagerie/franka_emika_panda/panda.xml, the world down to the hand frame.",
        )
        .with_documentation(
            "The Franka Panda arm: the seven turning joints from the base up to the hand, with the base and the hand as welds.",
        );
    let source = model
        .to_rust_source(&options)
        .unwrap_or_else(|e| unreachable!("write source for {input:?}: {e}"));

    std::fs::write(&output, source).unwrap_or_else(|e| unreachable!("write {output:?}: {e}"));
    println!("wrote {}", output.display());
}
